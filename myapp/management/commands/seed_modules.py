class Command(BaseCommand):
    help = "Создаёт модули курса 2–7 из реальных текстов упражнений бота. Модуль 1 не трогает."

    def add_arguments(self, parser):
        parser.add_argument('--yes', action='store_true',
                             help='Реально записать в базу (без флага — только показать, что будет сделано)')
        parser.add_argument('--force', action='store_true',
                             help='Перезаписать модули, которые уже существуют (по умолчанию — пропускаются)')
        parser.add_argument('--number', type=int, default=None,
                             help='Ограничиться одним модулем по номеру (например --number 2) — '
                                  'не трогать остальные, даже с --force')

    def handle(self, *args, **options):
        do_write = options['yes']
        force = options['force']
        only_number = options['number']

        modules = MODULES if only_number is None else [m for m in MODULES if m['number'] == only_number]
        if only_number is not None and not modules:
            self.stdout.write(self.style.ERROR(f"Модуль с номером {only_number} не найден в MODULES (2-7)."))
            return

        to_create, to_update, to_skip = [], [], []
        for data in modules:
            exists = Module.objects.filter(number=data['number']).exists()
            if exists and not force:
                to_skip.append(data)
            elif exists:
                to_update.append(data)
            else:
                to_create.append(data)

        for data in to_create:
            self.stdout.write(f"  создать: модуль {data['number']} «{data['title']}»")
        for data in to_update:
            self.stdout.write(self.style.WARNING(
                f"  ПЕРЕЗАПИСАТЬ (--force): модуль {data['number']} «{data['title']}» — уже существует"))
        for data in to_skip:
            self.stdout.write(f"  пропустить: модуль {data['number']} уже существует (без --force не трогаю)")

        if not do_write:
            self.stdout.write(self.style.WARNING(
                "\nЭто был предпросмотр. Ничего не записано. Чтобы записать по-настоящему — добавь --yes."
            ))
            return

        count = 0
        for i, data in enumerate(to_create + to_update, start=1):
            number = data['number']
            defaults = {k: v for k, v in data.items() if k != 'number'}
            defaults.setdefault('is_published', True)
            defaults['order'] = number
            # Простая раскладка на 3D-карте: по кругу вокруг центра, радиус растёт с номером.
            import math
            angle = math.radians((number - 2) * 55)
            radius = 6 + (number - 2) * 2.5
            defaults['position_x'] = round(radius * math.cos(angle), 2)
            defaults['position_z'] = round(radius * math.sin(angle), 2)
            Module.objects.update_or_create(number=number, defaults=defaults)
            count += 1

        self.stdout.write(self.style.SUCCESS(f"\nГотово — записано модулей: {count}."))
